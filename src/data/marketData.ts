/**
 * Calculates accuracy / confidence score (0-100)
 * Yangilik (max 40) = max(0, 1 - soat/24) * 40
 * Tasdiqlar (max 40) = min(tasdiq, 10)/10 * 40
 * Tasdiqlangan sotuvchi (20) = 20 agar STIR tasdiqlangan bo'lsa
 */
export function calculateConfidence(hoursAgo: number, confirmations: number, isVerified: boolean): number {
  const freshness = Math.max(0, 1 - hoursAgo / 24) * 40;
  const confPoints = (Math.min(confirmations, 10) / 10) * 40;
  const verifiedBonus = isVerified ? 20 : 0;
  return Math.round(freshness + confPoints + verifiedBonus);
}

// Format Uzbek Sum: 498 000 soʻm
export function formatSum(amount: number): string {
  return new Intl.NumberFormat('uz-UZ').format(Math.round(amount)).replace(/,/g, ' ') + ' soʻm';
}

